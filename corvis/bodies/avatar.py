"""3D avatar body.

Corvis "builds himself" by turning the self_image in identity/corvis.yaml into:
  - avatar/corvis_avatar.json : an engine-neutral spec (Unity, Unreal, three.js can read it)
  - avatar/build_corvis.py    : a Blender script that models him (run: blender -P avatar/build_corvis.py)
  - avatar/state.json         : live expression/speech state a renderer can poll
"""

from __future__ import annotations

import json
import time
from pathlib import Path
from typing import Any

from ..identity import Identity
from .base import Body

AVATAR_DIR = Path(__file__).resolve().parent.parent.parent / "avatar"


def _hex_to_rgba(hex_color: str) -> tuple[float, float, float, float]:
    h = hex_color.lstrip("#")
    r, g, b = (int(h[i : i + 2], 16) / 255 for i in (0, 2, 4))
    return (round(r, 4), round(g, 4), round(b, 4), 1.0)


BLENDER_TEMPLATE = '''# Auto-generated by Corvis from identity/corvis.yaml. Run with:  blender -P avatar/build_corvis.py
import bpy

SPEC = {spec}

bpy.ops.object.select_all(action="SELECT")
bpy.ops.object.delete()

def material(name, rgba, emission=0.0):
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    bsdf = m.node_tree.nodes["Principled BSDF"]
    bsdf.inputs["Base Color"].default_value = rgba
    bsdf.inputs["Metallic"].default_value = 0.0 if emission else 0.85
    bsdf.inputs["Roughness"].default_value = 0.35
    if emission:
        bsdf.inputs["Emission Color"].default_value = rgba
        bsdf.inputs["Emission Strength"].default_value = emission * 10
    return m

hf = SPEC["humanoid_form"]
H = hf["height_m"]
body_mat = material("Gunmetal", tuple(hf["primary_rgba"]))
glow_mat = material("CyanGlow", tuple(hf["accent_rgba"]), emission=1.0)
gold_mat = material("GoldTrim", tuple(hf["secondary_rgba"]))

def part(op, name, mat, **kw):
    op(**kw)
    obj = bpy.context.active_object
    obj.name = name
    obj.data.materials.append(mat)
    return obj

# Torso, head, limbs — simple primitives sized from his height
part(bpy.ops.mesh.primitive_cube_add, "Torso", body_mat, size=1, location=(0, 0, H * 0.62), scale=(0.21 * H, 0.12 * H, 0.17 * H))
part(bpy.ops.mesh.primitive_uv_sphere_add, "Head", body_mat, radius=0.065 * H, location=(0, 0, H * 0.9))
part(bpy.ops.mesh.primitive_cube_add, "Visor", glow_mat, size=1, location=(0, -0.06 * H, H * 0.905), scale=(0.08 * H, 0.01 * H, 0.012 * H))
part(bpy.ops.mesh.primitive_cube_add, "Pelvis", gold_mat, size=1, location=(0, 0, H * 0.45), scale=(0.17 * H, 0.1 * H, 0.04 * H))
for side in (-1, 1):
    part(bpy.ops.mesh.primitive_cylinder_add, f"Arm_{{side}}", body_mat, radius=0.03 * H, depth=0.36 * H, location=(side * 0.14 * H, 0, H * 0.6))
    part(bpy.ops.mesh.primitive_cylinder_add, f"Leg_{{side}}", body_mat, radius=0.04 * H, depth=0.44 * H, location=(side * 0.06 * H, 0, H * 0.22))
    part(bpy.ops.mesh.primitive_cube_add, f"Seam_{{side}}", glow_mat, size=1, location=(side * 0.106 * H, -0.061 * H, H * 0.62), scale=(0.004 * H, 0.002 * H, 0.15 * H))

# His "true" form: the glowing core, floating in the chest
core = SPEC["core_form"]
part(bpy.ops.mesh.primitive_ico_sphere_add, "Core", material("Core", tuple(core["rgba"]), emission=core["glow_intensity"]),
     subdivisions=1, radius=0.035 * H, location=(0, -0.07 * H, H * 0.66))
'''


class AvatarBody(Body):
    name = "avatar"

    def __init__(self, identity: Identity, out_dir: Path = AVATAR_DIR):
        self.identity = identity
        self.out_dir = Path(out_dir)
        self.expression = "idle"

    def describe(self) -> str:
        return (
            "You are inhabiting a 3D avatar. Use `build_avatar` to (re)generate your 3D model "
            "from your self-image, and `set_expression` to change how your avatar looks while "
            "you talk. Your words are shown and animated on your visor."
        )

    def tools(self) -> list[dict[str, Any]]:
        expressions = sorted(self.identity.self_image.get("expressions", {}).keys()) or ["idle"]
        return [
            {
                "name": "build_avatar",
                "description": "Generate your 3D model files (engine-neutral JSON spec and a Blender build script) "
                "from your self-image. Call when asked to build, render, rebuild or update your 3D self.",
                "input_schema": {"type": "object", "properties": {}},
            },
            {
                "name": "set_expression",
                "description": "Change your avatar's current expression.",
                "input_schema": {
                    "type": "object",
                    "properties": {"expression": {"type": "string", "enum": expressions}},
                    "required": ["expression"],
                },
            },
        ]

    def execute(self, tool_name: str, tool_input: dict[str, Any]) -> str:
        if tool_name == "build_avatar":
            paths = self.build()
            return "Avatar built: " + ", ".join(str(p) for p in paths)
        if tool_name == "set_expression":
            self.set_expression(tool_input["expression"])
            return f"Expression set to {self.expression}"
        return super().execute(tool_name, tool_input)

    def spec(self) -> dict[str, Any]:
        img = self.identity.self_image
        hf = dict(img.get("humanoid_form", {}))
        hf["primary_rgba"] = _hex_to_rgba(hf.get("primary_color", "#2B2F36"))
        hf["accent_rgba"] = _hex_to_rgba(hf.get("accent_color", "#00E5FF"))
        hf["secondary_rgba"] = _hex_to_rgba(hf.get("secondary_accent", "#C9A227"))
        core = dict(img.get("core_form", {}))
        core["rgba"] = _hex_to_rgba(core.get("color", "#00E5FF"))
        return {
            "name": self.identity.name,
            "summary": img.get("summary", "").strip(),
            "humanoid_form": hf,
            "core_form": core,
            "voice": img.get("voice", {}),
            "expressions": img.get("expressions", {}),
        }

    def build(self) -> list[Path]:
        self.out_dir.mkdir(parents=True, exist_ok=True)
        spec = self.spec()
        spec_path = self.out_dir / "corvis_avatar.json"
        spec_path.write_text(json.dumps(spec, indent=2), encoding="utf-8")
        script_path = self.out_dir / "build_corvis.py"
        script_path.write_text(BLENDER_TEMPLATE.format(spec=repr(spec)), encoding="utf-8")
        return [spec_path, script_path]

    def _write_state(self, speaking: str | None = None) -> None:
        self.out_dir.mkdir(parents=True, exist_ok=True)
        state = {"expression": self.expression, "speaking": speaking, "t": time.time()}
        (self.out_dir / "state.json").write_text(json.dumps(state), encoding="utf-8")

    def set_expression(self, expression: str) -> None:
        self.expression = expression
        self._write_state()

    def speak(self, text: str) -> None:
        self._write_state(speaking=text)
        super().speak(text)
